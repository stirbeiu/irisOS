#!/usr/bin/env python3
"""
irisOS - Unsplash Wallpaper Fetcher & Lossless QOI Encoder

Downloads a photographic wallpaper from Unsplash (preserving its native aspect
ratio so iris_compositor can dynamically aspect-fill any screen resolution at
runtime) and encodes it into resources/wallpaper/wallpaper.qoi.
"""

import os
import sys
import struct
import urllib.request
import subprocess
import tempfile

# Unsplash landscape autumn leaves / nature photography URL
UNSPLASH_AUTUMN_URL = (
    "https://images.unsplash.com/photo-1507525428034-b723cf961d3e"
    "?auto=format&fit=max&w=1440&q=85"
)


def encode_qoi_rgb(width: int, height: int, rgb_bytes: bytes) -> bytes:
    """Encode raw 24-bit RGB888 pixel buffer into a standard QOI (Quite OK Image) file."""
    QOI_OP_RGB = 0xFE
    QOI_OP_INDEX = 0x00
    QOI_OP_DIFF = 0x40
    QOI_OP_LUMA = 0x80
    QOI_OP_RUN = 0xC0

    out = bytearray()
    # 14-byte QOI header: magic "qoif", width (BE32), height (BE32), channels=3, colorspace=0
    out.extend(struct.pack(">4sIIBB", b"qoif", width, height, 3, 0))

    index = [(0, 0, 0, 0)] * 64
    prev_r, prev_g, prev_b, prev_a = 0, 0, 0, 255
    run = 0
    total_px = width * height
    mv = memoryview(rgb_bytes)

    for px_idx in range(total_px):
        off = px_idx * 3
        r = mv[off]
        g = mv[off + 1]
        b = mv[off + 2]
        a = 255

        if r == prev_r and g == prev_g and b == prev_b:
            run += 1
            if run == 62 or px_idx == total_px - 1:
                out.append(QOI_OP_RUN | (run - 1))
                run = 0
        else:
            if run > 0:
                out.append(QOI_OP_RUN | (run - 1))
                run = 0

            idx_pos = (r * 3 + g * 5 + b * 7 + a * 11) & 63
            if index[idx_pos] == (r, g, b, a):
                out.append(QOI_OP_INDEX | idx_pos)
            else:
                index[idx_pos] = (r, g, b, a)
                vr = ((r - prev_r) + 128) % 256 - 128
                vg = ((g - prev_g) + 128) % 256 - 128
                vb = ((b - prev_b) + 128) % 256 - 128
                vg_r = vr - vg
                vg_b = vb - vg

                if -2 <= vr <= 1 and -2 <= vg <= 1 and -2 <= vb <= 1:
                    out.append(QOI_OP_DIFF | ((vr + 2) << 4) | ((vg + 2) << 2) | (vb + 2))
                elif -32 <= vg <= 31 and -8 <= vg_r <= 7 and -8 <= vg_b <= 7:
                    out.append(QOI_OP_LUMA | (vg + 32))
                    out.append(((vg_r + 8) << 4) | (vg_b + 8))
                else:
                    out.append(QOI_OP_RGB)
                    out.append(r)
                    out.append(g)
                    out.append(b)

            prev_r, prev_g, prev_b = r, g, b

    # 8-byte QOI end marker
    out.extend(b"\x00\x00\x00\x00\x00\x00\x00\x01")
    return bytes(out)


def parse_bmp_to_rgb(bmp_path: str):
    """Read a 24-bit or 32-bit uncompressed BMP generated by macOS sips."""
    with open(bmp_path, "rb") as f:
        data = f.read()
    if data[:2] != b"BM":
        raise ValueError("Invalid BMP file")
    pixel_offset = struct.unpack_from("<I", data, 10)[0]
    width, height = struct.unpack_from("<ii", data, 18)
    bpp = struct.unpack_from("<H", data, 28)[0]
    top_down = height < 0
    abs_h = abs(height)
    bytes_per_px = bpp // 8
    row_stride = ((width * bytes_per_px + 3) // 4) * 4

    rgb = bytearray(width * abs_h * 3)
    for y in range(abs_h):
        src_y = y if top_down else (abs_h - 1 - y)
        row_start = pixel_offset + src_y * row_stride
        dst_start = y * width * 3
        for x in range(width):
            px_off = row_start + x * bytes_per_px
            b = data[px_off]
            g = data[px_off + 1]
            r = data[px_off + 2]
            d_off = dst_start + x * 3
            rgb[d_off] = r
            rgb[d_off + 1] = g
            rgb[d_off + 2] = b
    return width, abs_h, bytes(rgb)


def main():
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = os.path.join(root_dir, "resources", "wallpaper")
    os.makedirs(out_dir, exist_ok=True)
    out_qoi = os.path.join(out_dir, "wallpaper.qoi")

    url = sys.argv[1] if len(sys.argv) > 1 else UNSPLASH_AUTUMN_URL
    print(f"==> Downloading wallpaper from Unsplash: {url}")

    with tempfile.TemporaryDirectory() as tmpdir:
        jpg_path = os.path.join(tmpdir, "unsplash.jpg")
        bmp_path = os.path.join(tmpdir, "unsplash.bmp")
        req = urllib.request.Request(url, headers={"User-Agent": "irisOS-Wallpaper-Fetcher/1.0"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            with open(jpg_path, "wb") as f:
                f.write(resp.read())

        # Use macOS sips to decode JPEG into BMP at native aspect ratio (max dimension 1440 so QOI fits in 32MB System_A)
        subprocess.run(
            ["/usr/bin/sips", "-Z", "1440", "-s", "format", "bmp", jpg_path, "--out", bmp_path],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        w, h, rgb = parse_bmp_to_rgb(bmp_path)
        print(f"==> Encoding {w}x{h} wallpaper (native aspect ratio) to QOI...")
        qoi_data = encode_qoi_rgb(w, h, rgb)
        with open(out_qoi, "wb") as f:
            f.write(qoi_data)

    print(f"==> Wrote {out_qoi} ({len(qoi_data) / 1024:.1f} KB, {w}x{h})")


if __name__ == "__main__":
    main()
